import esbuild from "esbuild";
import process from "process";
import { readFileSync, writeFileSync } from "node:fs";
import { builtinModules } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { pife } from "./scripts/pife.mjs";

const here = dirname(fileURLToPath(import.meta.url));

const prod = process.argv[2] === "production";

const context = await esbuild.context({
  banner: { js: "/* mehrpele — generated by esbuild; do not edit */" },
  entryPoints: ["main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtinModules,
    ...builtinModules.map((m) => `node:${m}`),
  ],
  format: "cjs",
  // The rendering helpers live in lib/pele-render and are bundled from source,
  // so Pele is loaded once, through lib/pele-render/pele.ts.
  alias: {
    "pele-render/repair": resolve(here, "lib/pele-render/repair/index.ts"),
    "pele-render/canvas": resolve(here, "lib/pele-render/canvas/index.ts"),
    "pele-render/pele": resolve(here, "lib/pele-render/pele.ts"),
    "pele-render/node-size": resolve(here, "lib/pele-render/node-size/index.ts"),
    "pele-render/reflow": resolve(here, "lib/pele-render/reflow/index.ts"),
    "pele-render/excalidraw": resolve(here, "lib/pele-render/excalidraw/index.ts"),
    "pele-render/extract": resolve(here, "lib/pele-render/extract.ts"),
  },
  target: "es2020",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  minify: prod,
  outfile: "main.js",
});

if (prod) {
  await context.rebuild();
  await context.dispose();
  // Eager-compile hint for lazy module inits (see scripts/pife.mjs).
  const out = resolve(here, "main.js");
  const { code, wrapped } = pife(readFileSync(out, "utf8"));
  writeFileSync(out, code);
  console.log(`pife: wrapped ${wrapped} lazy module inits`);
  process.exit(0);
} else {
  await context.watch();
}
