/**
 * Data downloads: explainer clips and the tour-notes pack.
 *
 * - Data only. Nothing fetched here is ever run as code.
 * - Every asset is pinned (sha256 + size) at release time; unpinned names are never fetched.
 * - Fetched only on a user action (Play explainer, Install tour notes); never at load.
 * - Host: the public repo's release for this plugin version, so assets match the code.
 *
 * No runtime `obsidian` import: callers pass requestUrl, the adapter and the vault, so the
 * tests run against a loopback stub server.
 */

export interface AssetPin {
  sha256: string;
  bytes: number;
}

