export const ASSET_HOST = "https://github.com/Zpankz/obsidian-mehrpele/releases/download";
export const TOUR_FOLDER = "Mehrpele tour";

export interface HttpResponse {
  status: number;
  arrayBuffer: ArrayBuffer;
}
/** One GET. Resolves with any HTTP status; rejects only when no response arrived. */
export type HttpGet = (url: string) => Promise<HttpResponse>;

/** The slice of Obsidian's `requestUrl` this module needs. */
export type RequestUrlBinary = (req: {
  url: string;
  method: string;
  throw: boolean;
}) => Promise<{ status: number; arrayBuffer: ArrayBuffer }>;

/** HttpGet over `requestUrl` (CORS-free, works on mobile). */
export function requestUrlGet(requestUrl: RequestUrlBinary): HttpGet {
  return async (url) => {
    const r = await requestUrl({ url, method: "GET", throw: false });
    return { status: r.status, arrayBuffer: r.arrayBuffer };
  };
}

export type AssetErrorKind = "unpinned" | "offline" | "http" | "mismatch";

export class AssetFetchError extends Error {
  constructor(
    readonly kind: AssetErrorKind,
    message: string,
    readonly attempts = 0,
    readonly status?: number,
  ) {
    super(message);
    this.name = "AssetFetchError";
  }
}

const SAFE_NAME = /^[a-z0-9][a-z0-9._-]*$/i;

/** A plain file name: no folders, no `..`, no leading dot. */
function isSafeName(name: string): boolean {
  return SAFE_NAME.test(name) && !name.includes("..");
}

export function assetUrl(name: string, version: string, base: string = ASSET_HOST): string {
  return `${base.replace(/\/+$/, "")}/${encodeURIComponent(version)}/${encodeURIComponent(name)}`;
}

export async function sha256Hex(data: ArrayBuffer | Uint8Array): Promise<string> {
  // new Uint8Array(…) is backed by a plain ArrayBuffer, as digest requires (a view is copied).
  const digest = await crypto.subtle.digest("SHA-256", new Uint8Array(data));
  return Array.from(new Uint8Array(digest), (b) => b.toString(16).padStart(2, "0")).join("");
}

async function matchesPin(data: ArrayBuffer, pin: AssetPin): Promise<boolean> {
  return data.byteLength === pin.bytes && (await sha256Hex(data)) === pin.sha256;
}

export interface FetchOptions {
  get: HttpGet;
  /** The plugin version; the release tag the asset is read from. */
  version: string;
  /** Release host; tests point it at a loopback stub. */
  base?: string;
  pins?: Readonly<Record<string, AssetPin>>;
  tries?: number;
  retryDelayMs?: number;
  /** Per-request limit. requestUrl can't be cancelled, so a stalled request is abandoned. */
  timeoutMs?: number;
  sleep?: (ms: number) => Promise<void>;
}

const defaultSleep = (ms: number) => new Promise<void>((r) => window.setTimeout(r, ms));

function withTimeout<T>(p: Promise<T>, ms: number): Promise<T> {
  let timer: number | undefined;
  const timeout = new Promise<never>((_, reject) => {
    timer = window.setTimeout(() => reject(new Error(`no response after ${ms} ms`)), ms);
  });
  return Promise.race([p, timeout]).finally(() => window.clearTimeout(timer));
}

function pinFor(name: string, pins: Readonly<Record<string, AssetPin>>): AssetPin {
  const pin = isSafeName(name) ? pins[name] : undefined;
  if (!pin) throw new AssetFetchError("unpinned", `No pinned asset named "${name}"`);
  return pin;
}

/**
 * Download a pinned asset and verify it. Up to `tries` (3) attempts, retrying only when the
 * request throws or times out (offline, DNS, reset, stall) or the host answers 5xx. A 4xx or a hash mismatch is
 * final. Resolves with bytes that match the pin, or rejects with an AssetFetchError.
 */
export async function fetchPinned(name: string, opts: FetchOptions): Promise<ArrayBuffer> {
  const pin = pinFor(name, opts.pins ?? ASSET_PINS);
  const url = assetUrl(name, opts.version, opts.base);
  const tries = Math.max(1, opts.tries ?? 3);
  const delay = opts.retryDelayMs ?? 500;
  const sleep = opts.sleep ?? defaultSleep;
  let last: AssetFetchError | undefined;
  for (let attempt = 1; attempt <= tries; attempt++) {
    if (attempt > 1) await sleep(delay * 2 ** (attempt - 2));
    let res: HttpResponse;
    try {
      res = await withTimeout(opts.get(url), opts.timeoutMs ?? 15_000);
    } catch (e) {
      last = new AssetFetchError("offline", `Could not reach the download host: ${(e as Error)?.message ?? e}`, attempt);
      continue;
    }
    if (res.status >= 500) {
      last = new AssetFetchError("http", `Download host answered ${res.status}`, attempt, res.status);
      continue;
    }
    if (res.status < 200 || res.status >= 300) {
      throw new AssetFetchError("http", `Download host answered ${res.status}`, attempt, res.status);
    }
    if (!(await matchesPin(res.arrayBuffer, pin))) {
      throw new AssetFetchError("mismatch", "Download failed verification", attempt);
    }
    return res.arrayBuffer;
  }
  throw last!;
}

/** The slice of Obsidian's DataAdapter used for the plugin-private cache. */
export interface BinaryAdapter {
  exists(path: string): Promise<boolean>;
  readBinary(path: string): Promise<ArrayBuffer>;
  writeBinary(path: string, data: ArrayBuffer): Promise<void>;
  mkdir(path: string): Promise<void>;
}

export interface CacheOptions extends FetchOptions {
  adapter: BinaryAdapter;
  /** The plugin folder, `manifest.dir`. Assets go to `<dir>/assets/<name>`. */
  dir: string;
}

/** The cached copy when it still matches its pin; null otherwise. */
export async function cachedAsset(
  name: string,
  opts: Pick<CacheOptions, "adapter" | "dir" | "pins">,
): Promise<ArrayBuffer | null> {
  const pin = pinFor(name, opts.pins ?? ASSET_PINS);
  const path = `${opts.dir}/assets/${name}`;
  if (!(await opts.adapter.exists(path))) return null;
  const data = await opts.adapter.readBinary(path).catch(() => null);
  return data && (await matchesPin(data, pin)) ? data : null;
}

/**
 * A verified asset: the cached copy if it matches its pin, else a fresh download written to
 * the cache. Bytes are written only after they verify, so a failed download leaves no file.
 */
export async function ensureAsset(
  name: string,
  opts: CacheOptions,
): Promise<{ path: string; data: ArrayBuffer; fromCache: boolean }> {
  const path = `${opts.dir}/assets/${name}`;
  const cached = await cachedAsset(name, opts);
  if (cached) return { path, data: cached, fromCache: true };
  const data = await fetchPinned(name, opts);
  const folder = `${opts.dir}/assets`;
  if (!(await opts.adapter.exists(folder))) await opts.adapter.mkdir(folder);
  await opts.adapter.writeBinary(path, data);
  return { path, data, fromCache: false };
}

// ---- Tour notes pack (tour-<version>.json) ----

export interface TourNote {
  /** Path inside the tour folder, `/`-separated. */
  path: string;
  content: string;
}
export interface TourPack {
  version: string;
  notes: TourNote[];
}

const TOUR_EXT = /\.(md|base|canvas)$/;

function isSafeTourPath(p: string): boolean {
  if (!TOUR_EXT.test(p) || p.includes("\\") || p.startsWith("/")) return false;
  return p.split("/").every((seg) => seg !== "" && seg !== "." && seg !== ".." && !seg.startsWith("."));
}

/** Parse and validate a downloaded pack. Throws on any malformed shape or unsafe path. */
export function parseTourPack(data: ArrayBuffer): TourPack {
  const raw = JSON.parse(new TextDecoder().decode(data)) as unknown;
  const pack = raw as Partial<TourPack> | null;
  if (!pack || typeof pack.version !== "string" || !Array.isArray(pack.notes)) {
    throw new Error("Not a tour pack");
  }
  const notes = pack.notes.map((n) => {
    const note = n as Partial<TourNote> | null;
    if (!note || typeof note.path !== "string" || typeof note.content !== "string") throw new Error("Bad tour note");
    if (!isSafeTourPath(note.path)) throw new Error(`Unsafe tour path: ${note.path}`);
    return { path: note.path, content: note.content };
  });
  return { version: pack.version, notes };
}

/** The slice of Obsidian's Vault (plus FileManager.trashFile) the tour needs. */
export interface TourVault {
  getAbstractFileByPath(path: string): unknown;
  getFiles(): { path: string }[];
  createFolder(path: string): Promise<unknown>;
  create(path: string, data: string): Promise<unknown>;
  read(file: unknown): Promise<string>;
  trash(file: unknown): Promise<void>;
}

async function ensureFolder(vault: TourVault, path: string): Promise<void> {
  let acc = "";
  for (const seg of path.split("/")) {
    acc = acc ? `${acc}/${seg}` : seg;
    if (!vault.getAbstractFileByPath(acc)) await vault.createFolder(acc);
  }
}

function withSuffix(path: string, n: number): string {
  const dot = path.lastIndexOf(".");
  return `${path.slice(0, dot)} (${n})${path.slice(dot)}`;
}

/** Write the pack into the vault. Never overwrites: a taken name gets " (2)", " (3)", … */
export async function installTourNotes(
  vault: TourVault,
  pack: TourPack,
  folder: string = TOUR_FOLDER,
): Promise<{ created: string[] }> {
  const created: string[] = [];
  for (const note of pack.notes) {
    const target = `${folder}/${note.path}`;
    await ensureFolder(vault, target.slice(0, target.lastIndexOf("/")));
    let path = target;
    for (let n = 2; vault.getAbstractFileByPath(path); n++) path = withSuffix(target, n);
    await vault.create(path, note.content);
    created.push(path);
  }
  return { created };
}

/**
 * Trash the tour files that are unchanged from the pack, including the " (2)", " (3)", …
 * copies a repeat install made (even if some are gone); keep anything the user edited.
 */
export async function removeTourNotes(
  vault: TourVault,
  pack: TourPack,
  folder: string = TOUR_FOLDER,
): Promise<{ removed: string[]; kept: string[] }> {
  const removed: string[] = [];
  const kept: string[] = [];
  const all = vault.getFiles();
  const esc = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  for (const note of pack.notes) {
    const target = `${folder}/${note.path}`;
    const dot = target.lastIndexOf(".");
    const copy = new RegExp(`^${esc(target.slice(0, dot))} \\(\\d+\\)${esc(target.slice(dot))}$`);
    const paths = all.map((f) => f.path).filter((p) => p === target || copy.test(p));
    for (const path of paths.sort()) {
      const file = vault.getAbstractFileByPath(path);
      if (!file) continue;
      if ((await vault.read(file)) === note.content) {
        await vault.trash(file);
        removed.push(path);
      } else kept.push(path);
    }
  }
  return { removed, kept };
}
